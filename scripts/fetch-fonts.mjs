/**
 * Self-host the site's web fonts: `node scripts/fetch-fonts.mjs`.
 *
 * Downloads the Google Fonts woff2 files (latin, latin-ext and greek subsets)
 * into public/fonts/ with content-hashed names, writes public/fonts.css with
 * the matching @font-face rules (outside /fonts, whose hashed files are cached
 * immutable), and rewrites the preload tags between the fonts:begin/end
 * markers in index.html. All committed: run this only when the family list
 * below changes.
 *
 * Why: from Google the stylesheet was a cross-origin, render-blocking hop and
 * the files arrived after first paint, so the page painted in fallback fonts
 * and then swapped. Same-origin files can be preloaded (index.html) and cached
 * as immutable (public/_headers).
 */
import { createHash } from "node:crypto"
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const FAMILIES =
  "family=EB+Garamond:wght@400" +
  "&family=IBM+Plex+Mono:ital,wght@0,400;1,400" +
  "&family=IBM+Plex+Sans:ital,wght@0,300;0,400;0,500;0,600;1,400" +
  "&family=Playfair+Display:ital,wght@0,400;0,500;0,600;1,400" +
  "&family=UnifrakturMaguntia"
const SUBSETS = new Set(["latin", "latin-ext", "greek"])
// A modern UA, so Google answers with woff2 and variable files where it has them.
const UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36"
const OUT = join(import.meta.dirname, "..", "public", "fonts")
const INDEX = join(import.meta.dirname, "..", "index.html")
// Above the fold on every page: body text and headings. The rest load on use.
const PRELOAD = ["ibm-plex-sans-normal-latin.", "playfair-display-normal-latin."]

const css = await (await fetch(`https://fonts.googleapis.com/css2?${FAMILIES}&display=swap`, { headers: { "User-Agent": UA } })).text()

mkdirSync(OUT, { recursive: true })
for (const f of readdirSync(OUT)) rmSync(join(OUT, f))

const files = new Map() // google url -> local name (variable fonts share one file across weights)
const rules = []
for (const m of css.matchAll(/\/\* ([a-z-]+) \*\/\s*@font-face \{([^}]+)\}/g)) {
  const [, subset, body] = m
  if (!SUBSETS.has(subset)) continue
  const url = body.match(/url\(([^)]+)\)/)[1]
  const family = body.match(/font-family: '([^']+)'/)[1]
  const style = body.match(/font-style: (\w+)/)[1]
  if (!files.has(url)) {
    const bytes = Buffer.from(await (await fetch(url, { headers: { "User-Agent": UA } })).arrayBuffer())
    const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 8)
    const name = `${family.toLowerCase().replace(/\s+/g, "-")}-${style}-${subset}.${hash}.woff2`
    writeFileSync(join(OUT, name), bytes)
    files.set(url, name)
  }
  rules.push(`/* ${subset} */\n@font-face {${body.replace(url, `/fonts/${files.get(url)}`)}}`)
}

writeFileSync(
  join(OUT, "..", "fonts.css"),
  `/* Generated by scripts/fetch-fonts.mjs. Do not edit by hand. */\n${rules.join("\n")}\n`,
)
const preloads = [...files.values()]
  .filter((name) => PRELOAD.some((prefix) => name.startsWith(prefix)))
  .map((name) => `    <link rel="preload" href="/fonts/${name}" as="font" type="font/woff2" crossorigin />`)
const html = readFileSync(INDEX, "utf-8")
const eol = html.includes("\r\n") ? "\r\n" : "\n"
const marked = /(<!-- fonts:begin[^>]*-->\r?\n)[\s\S]*?( *<!-- fonts:end -->)/
if (!marked.test(html)) throw new Error("index.html lost its <!-- fonts:begin/end --> markers")
writeFileSync(INDEX, html.replace(marked, `$1${preloads.map((l) => l + eol).join("")}$2`))
console.log(`fonts: ${files.size} files, ${rules.length} rules, ${preloads.length} preloads`)
for (const name of files.values()) if (name.includes("-latin.")) console.log("  ", name)
